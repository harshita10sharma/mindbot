_DAYS = {"daily": range(0, 7), "mon-sat": range(0, 6), "mon-fri": range(0, 5)}


def digits(s: str) -> str:
    return re.sub(r"\D", "", s)


def verified_numbers() -> Set[str]:
    """All verified numbers as digit strings, with and without the India country code."""
    out: Set[str] = set()
    for r in DIRECTORY:
        for key in ("phone", "alt"):
            if r.get(key):
                d = digits(r[key])
                out |= {d, d[2:] if d.startswith("91") and len(d) > 10 else d, d.lstrip("0")}
    return out


def is_open(r: Dict[str, Any], now: Optional[datetime] = None) -> Optional[bool]:
    """True/False if hours are known, None if unverified."""
    hours = r.get("hours")
    if hours is None:
        return True
    if hours == "unverified":
        return None
    now = now or datetime.now(IST)
    days, start, end = hours
    hhmm = now.strftime("%H:%M")
    return now.weekday() in _DAYS[days] and start <= hhmm < end


def describe(r: Dict[str, Any], now: Optional[datetime] = None) -> str:
    hours = r.get("hours")
    when = "24x7" if hours is None else "hours vary" if hours == "unverified" else f"{hours[0]} {hours[1]}-{hours[2]} IST"
    extra = f", or {r['alt']}" if r.get("alt") else ""
    email = f", email {r['email']}" if r.get("email") else ""
    chans = "/".join(r.get("channels", ["call"]))
    return f"{r['name']}: {r['phone']}{extra}{email} ({chans}, {when})"


def select(need: str = "crisis", language: str = "english", region: str = "India", k: int = 3,
           now: Optional[datetime] = None) -> List[Dict[str, Any]]:
    """Pick services that are relevant AND open right now.
    need: 'imminent' | 'crisis' | 'talk' (wants a real person / counsellor)."""
    now = now or datetime.now(IST)
    lang = {"hinglish": "hindi"}.get(language, language)
    pool = [r for r in DIRECTORY if r["region"] in (region, "India") or r["type"] == "emergency"]
    pool = [r for r in pool if r["region"] == region or r["region"] == "India"]

    def score(r):
        s = 0
        if is_open(r, now) is True:
            s += 10
        elif is_open(r, now) is None:
            s += 2
        if lang in r["languages"] or "all" in r["languages"]:
            s += 3
        if need in ("crisis", "imminent") and r["type"] == "crisis":
            s += 5
        if need == "talk" and r["type"] == "counselling":
            s += 6
        if r["id"] == "tele_manas":
            s += 4  # national, free, multilingual, 24x7: always a strong default
        return s

    candidates = [r for r in pool if r["type"] in ("crisis", "counselling") and is_open(r, now) is not False]
    chosen = sorted(candidates, key=score, reverse=True)[:k]
    if need == "imminent":
        chosen = [r for r in DIRECTORY if r["id"] == "emergency_112"] + chosen[: k - 1]
    return chosen


def public(rs: List[Dict[str, Any]], now: Optional[datetime] = None) -> List[Dict[str, Any]]:
    """Shape for the API / frontend crisis card."""
    return [{"name": r["name"], "contact": r["phone"], "alt": r.get("alt"), "email": r.get("email"),
             "channels": r.get("channels"), "open_now": is_open(r, now), "region": r["region"],
             "about": r.get("about", "")} for r in rs]


